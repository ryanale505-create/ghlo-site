// واجهة المحادثة مع الذكاء الاصطناعي
// ========================================

app.post("/api/chat", async (req, res) => {
  try {
    const { message, history = [] } = req.body || {};

    // التحقق من الرسالة
    if (
      typeof message !== "string" ||
      !message.trim()
    ) {
      return res.status(400).json({
        error: "اكتب رسالة أولاً ❤️"
      });
    }

    // التحقق من مفتاح API
    const apiKey = process.env.GROQ_API_KEY;

    if (!apiKey) {
      console.error("GROQ_API_KEY is missing!");

      return res.status(500).json({
        error: "مفتاح الذكاء الاصطناعي غير موجود."
      });
    }

    // تنظيف سجل المحادثة
    const safeHistory = Array.isArray(history)
      ? history
          .filter(
            (item) =>
              item &&
              ["user", "assistant"].includes(item.role) &&
              typeof item.content === "string"
          )
          .slice(-20)
          .map((item) => ({
            role: item.role,
            content: item.content.slice(0, 2000)
          }))
      : [];

    // الاتصال بخدمة Groq
    const groqResponse = await fetch(
      "https://api.groq.com/openai/v1/chat/completions",
      {
        method: "POST",

        headers: {
          Authorization: `Bearer ${apiKey.trim()}`,
          "Content-Type": "application/json"
        },

        body: JSON.stringify({
          model: "openai/gpt-oss-20b",

          messages: [
            {
              role: "system",
              content: systemPrompt
            },
            ...safeHistory,
            {
              role: "user",
              content: message.trim().slice(0, 2000)
            }
          ],

          temperature: 0.7,
          max_tokens: 800
        })
      }
    );

    // قراءة استجابة Groq
    const data = await groqResponse.json();

    // معالجة الأخطاء
    if (!groqResponse.ok) {
      console.error(
        "Groq Error:",
        groqResponse.status,
        data
      );

      return res.status(500).json({
        error:
          data.error?.message ||
          "حدث خطأ أثناء الاتصال بالذكاء الاصطناعي."
      });
    }

    // استخراج الرد
    const reply =
      data.choices?.[0]?.message?.content ||
      "ما قدرت أجهز لك رد الحين، حاول مرة ثانية ❤️";

    // إرسال الرد للموقع
    return res.json({ reply });

  } catch (error) {
    console.error("Server Error:", error);

    return res.status(500).json({
      error: "حدث خطأ في الاتصال، حاول مجدداً."
    });
  }
});

