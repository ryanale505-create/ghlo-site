app.post("/api/chat", async (req, res) => {
  try {
    const { message, history = [] } = req.body || {};

    if (
      typeof message !== "string" ||
      !message.trim()
    ) {
      return res.status(400).json({
        error: "اكتب رسالتك أولًا."
      });
    }

    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      console.error("GEMINI_API_KEY is missing.");

      return res.status(500).json({
        error: "مفتاح Gemini غير موجود في إعدادات Render."
      });
    }

    // تنظيف سجل المحادثة وتحويل assistant إلى model
    const safeHistory = Array.isArray(history)
      ? history
          .filter(
            (item) =>
              item &&
              ["user", "assistant", "model"].includes(item.role) &&
              typeof item.content === "string" &&
              item.content.trim()
          )
          .slice(-20)
          .map((item) => ({
            role:
              item.role === "assistant" ? "model" : item.role,
            parts: [
              {
                text: item.content.slice(0, 1500)
              }
            ]
          }))
      : [];

    const userMessage = message.trim().slice(0, 3000);

    const contents = [
      ...safeHistory,
      {
        role: "user",
        parts: [{ text: userMessage }]
      }
    ];

    const url =
      `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`;

    const geminiResponse = await fetch(url, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-goog-api-key": apiKey.trim()
      },
      body: JSON.stringify({
        systemInstruction: {
          parts: [{ text: systemPrompt }]
        },
        contents,
        generationConfig: {
          temperature: 0.85,
          maxOutputTokens: 1200
        }
      })
    });

    const data = await geminiResponse.json();

    if (!geminiResponse.ok) {
      const errorMessage =
        data?.error?.message || "Unknown Gemini API error";

      console.error("Gemini API Error:", {
        status: geminiResponse.status,
        message: errorMessage
      });

      if (geminiResponse.status === 400) {
        return res.status(400).json({
          error: "تعذر فهم الطلب. جرّب صياغة السؤال بطريقة أخرى."
        });
      }

      if (geminiResponse.status === 401 || geminiResponse.status === 403) {
        return res.status(500).json({
          error: "مفتاح Gemini غير صالح أو لا يملك الصلاحية المطلوبة."
        });
      }

      if (geminiResponse.status === 404) {
        return res.status(500).json({
          error: "الموديل غير متاح. تحقق من اسم الموديل في إعدادات الخادم."
        });
      }

      if (geminiResponse.status === 429) {
        return res.status(429).json({
          error: "وصلنا إلى حد الاستخدام مؤقتًا. انتظر قليلًا ثم حاول مرة ثانية."
        });
      }

      return res.status(502).json({
        error: "تعذر الاتصال بخدمة الذكاء الاصطناعي حاليًا."
      });
    }

    const reply =
      data?.candidates?.[0]?.content?.parts
        ?.map((part) => part.text || "")
        .join("")
        .trim();

    if (!reply) {
      console.error("Gemini returned no text:", data);

      return res.status(502).json({
        error: "وصل رد فارغ من الذكاء الاصطناعي. حاول مرة أخرى."
      });
    }

    return res.json({ reply });

  } catch (error) {
    console.error("Server Error:", error.message);

    return res.status(500).json({
      error: "حدث خطأ في الاتصال. حاول مرة أخرى بعد قليل."
    });
  }
});


