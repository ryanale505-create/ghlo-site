app.post("/api/chat", async (req, res) => {
  try {
    const { message, history = [] } = req.body || {};

    // التحقق من الرسالة
    if (
      typeof message !== "string" ||
      !message.trim()
    ) {
      return res.status(400).json({
        error: "اكتب رسالة أولاً ❤️"
      });
    }

    // مفتاح Gemini من إعدادات Render
    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      console.error("GEMINI_API_KEY is missing!");

      return res.status(500).json({
        error: "مفتاح Gemini غير موجود في إعدادات Render."
      });
    }

    // تنظيف سجل المحادثة
    const safeHistory = Array.isArray(history)
      ? history
          .filter(
            item =>
              item &&
              ["user", "assistant"].includes(item.role) &&
              typeof item.content === "string"
          )
          .slice(-6)
          .map(item => ({
            role: item.role === "assistant" ? "model" : "user",
            parts: [
              {
                text: item.content.slice(0, 1500)
              }
            ]
          }))
      : [];

    // الاتصال بـ Gemini
    const geminiResponse = await fetch(
      "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent",
      {
        method: "POST",

        headers: {
          "Content-Type": "application/json",
          "x-goog-api-key": apiKey.trim()
        },

        body: JSON.stringify({
          systemInstruction: {
            parts: [
              {
                text: systemPrompt
              }
            ]
          },

          contents: [
            ...safeHistory,
            {
              role: "user",
              parts: [
                {
                  text: message.trim().slice(0, 2000)
                }
              ]
            }
          ],

          tools: [
            {
              google_search: {}
            }
          ],

          generationConfig: {
            maxOutputTokens: 700,
            temperature: 0.7
          }
        })
      }
    );

    const data = await geminiResponse.json();

    // معالجة أخطاء Gemini
    if (!geminiResponse.ok) {
      console.error(
        "Gemini Error:",
        geminiResponse.status,
        data
      );

      return res.status(500).json({
        error:
          data.error?.message ||
          "حدث خطأ أثناء الاتصال بـ Gemini."
      });
    }

    // استخراج الرد
    const reply =
      data.candidates?.[0]?.content?.parts
        ?.map(part => part.text || "")
        .join("")
        .trim() ||
      "ما قدرت أجهز لك رد الحين، حاول مرة ثانية ❤️";

    return res.json({ reply });

  } catch (error) {
    console.error("Server Error:", error);

    return res.status(500).json({
      error: "تعذر الاتصال بالذكاء الاصطناعي، حاول مجددًا."
    });
  }
});

